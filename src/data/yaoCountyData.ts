/**
 * 按 provinceId 索引的县级数据缓存
 */
const countiesByProvinceCache = new Map<string, YaoCounty[]>();
for (const c of yaoCounties) {
  const list = countiesByProvinceCache.get(c.province) ?? [];
  list.push(c);
  countiesByProvinceCache.set(c.province, list);
}

/**
 * 按 code 索引的县级数据缓存
 */
const countyByCode = new Map<string, YaoCounty>(yaoCounties.map((c) => [c.code, c]));

/**
 * 按经纬度范围查询的辅助索引（极简桶分桶以加速空间查询）
 * 由于本项目县级数据量较小（<50），不做空间索引也够用
 */

/**
 * 按 province 名称获取其下辖瑶医瑶药重点县列表
 */
export const getCountiesByProvince = (province: string): YaoCounty[] =>
  countiesByProvinceCache.get(province) ?? [];

/**
 * 按 code 获取单个瑶医瑶药重点县
 */
export const getCountyByCode = (code: string): YaoCounty | undefined =>
  countyByCode.get(code);

/**
 * 按分类获取全部瑶医瑶药重点县
 */
export const getCountiesByCategory = (category: YaoCounty['category']): YaoCounty[] =>
  yaoCounties.filter((c) => c.category === category);

/**
 * 获取全部瑶医瑶药重点县总数
 */
export const getCountyTotalCount = (): number => yaoCounties.length;