// 按 regionId 缓存的索引，避免每次查询都全量 filter。
const herbsByRegionCache = new Map<string, Herb[]>();
const therapiesByRegionCache = new Map<string, Therapy[]>();
const historyByRegionCache = new Map<string, HistoryPeriod[]>();

export const getHerbsByRegion = (regionId: string): Herb[] => {
  let cached = herbsByRegionCache.get(regionId);
  if (!cached) {
    cached = herbs.filter((h) => h.regionId === regionId);
    herbsByRegionCache.set(regionId, cached);
  }
  return cached;
};

export const getTherapiesByRegion = (regionId: string): Therapy[] => {
  let cached = therapiesByRegionCache.get(regionId);
  if (!cached) {
    cached = therapies.filter((t) => t.regionId === regionId);
    therapiesByRegionCache.set(regionId, cached);
  }
  return cached;
};

export const getHistoryPeriodsByRegion = (regionId: string): HistoryPeriod[] => {
  let cached = historyByRegionCache.get(regionId);
  if (!cached) {
    cached = historyPeriods.filter((h) => h.regionId === regionId);
    historyByRegionCache.set(regionId, cached);
  }
  return cached;
};

// ID -> 实体的索引：仅构建一次，常用于点击/搜索跳转。
const herbById = new Map(herbs.map((h) => [h.id, h]));
const therapyById = new Map(therapies.map((t) => [t.id, t]));
const historyById = new Map(historyPeriods.map((h) => [h.id, h]));
const regionById = new Map(regions.map((r) => [r.id, r]));

export const getHerbById = (id: string) => herbById.get(id);
export const getTherapyById = (id: string) => therapyById.get(id);
export const getHistoryPeriodById = (id: string) => historyById.get(id);
export const getRegionById = (id: string) => regionById.get(id);

export const searchAll = (keyword: string): SearchResult[] => {
  const lowerKeyword = keyword.toLowerCase();
  const results: SearchResult[] = [];
  
  herbs.forEach(h => {
    if (h.name.toLowerCase().includes(lowerKeyword) || 
        h.nameEn.toLowerCase().includes(lowerKeyword) ||
        h.efficacy.toLowerCase().includes(lowerKeyword)) {
      results.push({
        type: 'herb',
        id: h.id,
        name: h.name,
        description: h.efficacy.substring(0, 50) + '...',
        regionId: h.regionId
      });
    }
  });
  
  therapies.forEach(t => {
    if (t.name.toLowerCase().includes(lowerKeyword) ||
        t.nameEn.toLowerCase().includes(lowerKeyword) ||
        t.description.toLowerCase().includes(lowerKeyword)) {
      results.push({
        type: 'therapy',
        id: t.id,
        name: t.name,
        description: t.description.substring(0, 50) + '...',
        regionId: t.regionId
      });
    }
  });
  
  historyPeriods.forEach(h => {
    if (h.periodName.toLowerCase().includes(lowerKeyword) ||
        h.description.toLowerCase().includes(lowerKeyword)) {
      results.push({
        type: 'history',
        id: h.id,
        name: h.periodName,
        description: h.description.substring(0, 50) + '...',
        regionId: h.regionId
      });
    }
  });
  
  return results;
};
