/**
 * 通过 code 查找扩展资料
 */
export function getYaoCountyExtendedByCode(code: string): YaoCountyExtended | undefined {
  return yaoCountiesExtended.find((c) => c.code === code);
}

/**
 * 通过省级 adcode 查找所有该省瑶医县
 */
export function getYaoCountiesExtendedByProvinceCode(provinceCode: string): YaoCountyExtended[] {
  return yaoCountiesExtended.filter((c) => c.provinceCode === provinceCode);
}

/**
 * 统计扩展资料完整性
 */
export function getYaoCountiesExtendedStatistics() {
  const stats = {
    total: yaoCountiesExtended.length,
    core: 0,
    development: 0,
    production: 0,
    totalHerbResources: 0,
    totalClinicalCases: 0,
    avgHospitalSupport: 0,
    totalInheritors: 0,
    withCultivationBase: 0,
    nationalHeritage: 0,
  };
  for (const c of yaoCountiesExtended) {
    if (c.category === 'core') stats.core++;
    else if (c.category === 'development') stats.development++;
    else if (c.category === 'production') stats.production++;
    stats.totalHerbResources += c.localHerbResources.length;
    stats.totalClinicalCases += c.clinicalCases.length;
    if (c.heritage.hasHospital) stats.avgHospitalSupport++;
    stats.totalInheritors += c.heritage.inheritorCount;
    if (c.heritage.hasCultivationBase) stats.withCultivationBase++;
    if (c.heritage.govSupportLevel === 'national') stats.nationalHeritage++;
  }
  return stats;
}